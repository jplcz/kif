#
"""`kif completion bash|zsh|fish`: shell completion scripts for `kif`, generated from the real argument parsers.

The command and option names come from the parsers of `kif`, `kif-check` and `kifc` themselves (`argparse`), so a new option
is completed without touching this file. Install, for example:

    kif completion bash > ~/.local/share/bash-completion/completions/kif
    kif completion zsh  > ~/.zfunc/_kif                 # with ~/.zfunc in $fpath
    kif completion fish > ~/.config/fish/completions/kif.fish
"""

from __future__ import annotations

import argparse
from typing import Dict, List, Optional

SHELLS = ("bash", "zsh", "fish")


class Opt:
    def __init__(self, flags: List[str], help: str, value: bool, choices: Optional[List[str]]) -> None:
        self.flags, self.help, self.value, self.choices = flags, help or "", value, choices


def _options(parser: argparse.ArgumentParser) -> List[Opt]:
    out = []
    for a in parser._actions:  # argparse has no public listing of a parser's options
        if not a.option_strings or isinstance(a, argparse._HelpAction):
            continue
        takes = a.nargs != 0
        out.append(Opt(list(a.option_strings), (a.help or "").split("\n")[0], takes, [str(c) for c in a.choices] if a.choices else None))
    return out


def model() -> Dict[str, dict]:
    """command -> {help, opts, files}: every `kif` subcommand with the options of the tool it runs."""
    from . import __main__ as check_main, kif, kifc, mimport  # noqa: F401  (mimport: its parser is built inline in main)

    ap, sub = kif.make_parser()
    help_of = {a.dest: a.help for a in sub._choices_actions}
    cmds: Dict[str, dict] = {}
    for name, p in sub.choices.items():
        cmds[name] = {"help": help_of.get(name) or "", "opts": _options(p), "files": True}
    _, check_sub = check_main.make_parser()
    for name in ("check", "export", "modules"):
        cmds[name]["opts"] = _options(check_sub.choices[name])
    cmds["modules"]["files"] = False
    cmds["build"]["opts"] = _options(kifc.make_parser())
    cmds["import-m"]["opts"] = [Opt(["-o", "--output"], "write here instead of standard output", True, None)]
    cmds["lsp"]["files"] = False
    cmds["completion"]["files"] = False
    cmds["completion"]["words"] = list(SHELLS)
    cmds["new"]["files"] = False
    cmds["new"]["opts"] = _options(sub.choices["new"])
    return cmds


def _flags(c: dict) -> List[str]:
    return [f for o in c["opts"] for f in o.flags]


def bash(cmds: Dict[str, dict]) -> str:
    cases = []
    for name, c in cmds.items():
        words = " ".join(_flags(c) + c.get("words", []))
        choice_cases = "".join(
            f'            {"|".join(o.flags)}) COMPREPLY=($(compgen -W "{" ".join(o.choices)}" -- "$cur")); return;;\n'
            for o in c["opts"] if o.choices)
        files = '            COMPREPLY+=($(compgen -f -X "!*.kif" -- "$cur") $(compgen -d -- "$cur"))\n' if c["files"] else ""
        cases.append(f'''        {name})
            case "$prev" in
{choice_cases}            esac
            COMPREPLY=($(compgen -W "{words}" -- "$cur"))
{files}            ;;''')
    return f'''# bash completion for kif (generated by `kif completion bash`)
_kif() {{
    local cur prev cmd
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    cmd="${{COMP_WORDS[1]}}"
    if [ "$COMP_CWORD" -eq 1 ]; then
        COMPREPLY=($(compgen -W "{" ".join(cmds)}" -- "$cur"))
        return
    fi
    case "$cmd" in
{chr(10).join(cases)}
    esac
}}
complete -o filenames -F _kif kif
'''


def _q(s: str) -> str:
    return s.replace("'", "'\\''").replace("[", "(").replace("]", ")").replace(":", " -")


def zsh(cmds: Dict[str, dict]) -> str:
    out = ["#compdef kif", "# zsh completion for kif (generated by `kif completion zsh`)", "_kif() {", "  local -a commands", "  commands=("]
    out += [f"    '{n}:{_q(c['help'])}'" for n, c in cmds.items()]
    out += ["  )", "  if (( CURRENT == 2 )); then _describe 'command' commands; return; fi", "  case $words[2] in"]
    for name, c in cmds.items():
        specs = []
        for o in c["opts"]:
            arg = (":value:(" + " ".join(o.choices) + ")" if o.choices else ":value:_files") if o.value else ""
            for f in o.flags:
                specs.append(f"'{f}[{_q(o.help)}]{arg}'")
        if c["files"]:
            specs.append("'*:file:_files -g \"*.kif\"'")
        if c.get("words"):
            specs.append("'1:shell:(" + " ".join(c["words"]) + ")'")
        out.append(f"    {name}) _arguments {' '.join(specs) if specs else ''} ;;")
    out += ["  esac", "}", '_kif "$@"', ""]
    return "\n".join(out)


def fish(cmds: Dict[str, dict]) -> str:
    out = ["# fish completion for kif (generated by `kif completion fish`)", "complete -c kif -f"]
    for name, c in cmds.items():
        out.append(f"complete -c kif -n '__fish_use_subcommand' -a {name} -d '{_q(c['help'])}'")
    for name, c in cmds.items():
        cond = f"'__fish_seen_subcommand_from {name}'"
        for o in c["opts"]:
            long = [f[2:] for f in o.flags if f.startswith("--")]
            short = [f[1:] for f in o.flags if f.startswith("-") and not f.startswith("--")]
            spec = "".join(f" -l {x}" for x in long) + "".join(f" -s {x}" for x in short)
            arg = (" -x -a '" + " ".join(o.choices) + "'" if o.choices else " -r") if o.value else ""
            out.append(f"complete -c kif -n {cond}{spec}{arg} -d '{_q(o.help)}'")
        for w in c.get("words", []):
            out.append(f"complete -c kif -n {cond} -a {w}")
        if c["files"]:
            out.append(f"complete -c kif -n {cond} -F")
    return "\n".join(out) + "\n"


def script(shell: str) -> str:
    if shell not in SHELLS:
        raise ValueError(f"unknown shell {shell!r} (one of {', '.join(SHELLS)})")
    return {"bash": bash, "zsh": zsh, "fish": fish}[shell](model())
