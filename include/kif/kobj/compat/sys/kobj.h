/**
 * @file kobj.h
 * @brief Drop-in replacement for FreeBSD's <sys/kobj.h> for userland, simulators and other non-FreeBSD targets.
 *
 * Same types, field layout and macros as FreeBSD (kobj_class, kobj_method, kobjop_desc, kobj_ops with the method
 * cache, KOBJMETHOD, DEFINE_CLASS_0..3, KOBJOPLOOKUP, base classes), so makeobjops output and `kifc --freebsd`
 * output compile unchanged. The implementation (kobj_c.cpp) allocates through reloco's allocators and is the only
 * part that needs C++. There is no kernel malloc: `mtype` and `mflags` are accepted and ignored (M_KOBJ is a null pointer).
 *
 * ## Allocators
 * - `kobj_create()` and the implicit `kobj_class_compile()` use `reloco::default_allocator()`.
 * - C callers pass an allocator as callbacks: `struct kif_allocator`.
 * - C++ callers pass a `reloco::allocator_ref` directly: `kif::kobj::create()`, `class_compile()`.
 *
 * ## Example (C)
 * @code
 * struct my_softc { struct kobj kobj; int x; };            // first member is the base kobj
 * static int my_read(kobj_t o, int a) { return ((struct my_softc *)o)->x + a; }
 * static kobj_method_t my_methods[] = { KOBJMETHOD(my_read, my_read), KOBJMETHOD_END };
 * DEFINE_CLASS_0(my, my_class, my_methods, sizeof(struct my_softc));
 *
 * kobj_t o = kobj_create(&my_class, M_KOBJ, M_WAITOK);     // heap object through reloco's default allocator
 * MY_READ(o, 1);                                           // wrapper generated by kifc / makeobjops
 * kobj_delete(o, M_KOBJ);                                  // unbinds and frees
 *
 * struct kif_allocator a = { my_alloc, my_free, &my_arena };     // C callbacks
 * kobj_t p = kif_kobj_create(&my_class, &a);           // object from your allocator
 * kif_kobj_destroy(p);                                 // always frees; uses the allocator remembered in p
 * @endcode
 *
 * ## Example (C++)
 * @code
 * reloco::allocator_ref arena = ...;                       // any reloco allocator; must outlive the object
 * kif::kobj::object_ptr o = kif::kobj::create(my_class, arena);
 * MY_READ(o.get(), 1);                                     // freed (through arena) when o goes out of scope
 * @endcode
 */

